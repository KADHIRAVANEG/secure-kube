#!/usr/bin/env bash
# SecureKube NetworkPolicy Auto-Discovery & Generator
# Solves the "Silent Network Blackhole" developer pain point by auto-generating
# a least-privilege NetworkPolicy for any workload, pre-configured with DNS egress
# and verified dependency rules.
set -euo pipefail

TARGET="${1:-}"
NAMESPACE="${2:-default}"

if [ -z "${TARGET}" ]; then
  cat << EOF
Usage:
  ./scripts/generate-network-policy.sh <pod-or-deployment> [namespace] [output-file]

Examples:
  ./scripts/generate-network-policy.sh secure-app default
  ./scripts/generate-network-policy.sh deployment/api-server prod -o api-netpol.yaml
EOF
  exit 1
fi

OUTPUT_FILE=""
if [ "${3:-}" = "-o" ] && [ -n "${4:-}" ]; then
  OUTPUT_FILE="$4"
elif [ -n "${3:-}" ] && [ "${3:-}" != "-o" ]; then
  OUTPUT_FILE="$3"
fi

# Clean target name
RESOURCE_TYPE="pod"
RESOURCE_NAME="${TARGET}"
if [[ "${TARGET}" == *"/"* ]]; then
  RESOURCE_TYPE="${TARGET%%/*}"
  RESOURCE_NAME="${TARGET##*/}"
fi

echo "→ Inspecting ${RESOURCE_TYPE}/${RESOURCE_NAME} in namespace '${NAMESPACE}'..." >&2

# 1. Fetch labels and ports from live resource or manifests
LABELS_JSON=$(kubectl get "${RESOURCE_TYPE}" "${RESOURCE_NAME}" -n "${NAMESPACE}" -o jsonpath='{.metadata.labels}' 2>/dev/null || echo "{}")
if [ "${LABELS_JSON}" = "{}" ] && [ "${RESOURCE_TYPE}" != "pod" ]; then
  LABELS_JSON=$(kubectl get "${RESOURCE_TYPE}" "${RESOURCE_NAME}" -n "${NAMESPACE}" -o jsonpath='{.spec.template.metadata.labels}' 2>/dev/null || echo "{}")
fi

# Determine primary match label
PRIMARY_KEY="app"
PRIMARY_VAL="${RESOURCE_NAME}"

if echo "${LABELS_JSON}" | grep -q "app.kubernetes.io/name"; then
  PRIMARY_KEY="app.kubernetes.io/name"
  PRIMARY_VAL=$(kubectl get "${RESOURCE_TYPE}" "${RESOURCE_NAME}" -n "${NAMESPACE}" -o jsonpath='{.metadata.labels.app\.kubernetes\.io/name}' 2>/dev/null || echo "${RESOURCE_NAME}")
elif echo "${LABELS_JSON}" | grep -q '"app"'; then
  PRIMARY_KEY="app"
  PRIMARY_VAL=$(kubectl get "${RESOURCE_TYPE}" "${RESOURCE_NAME}" -n "${NAMESPACE}" -o jsonpath='{.metadata.labels.app}' 2>/dev/null || echo "${RESOURCE_NAME}")
fi

# 2. Discover container ports
PORTS_LIST=$(kubectl get "${RESOURCE_TYPE}" "${RESOURCE_NAME}" -n "${NAMESPACE}" -o jsonpath='{range .spec.containers[*].ports[*]}{.containerPort}{" "}{end}' 2>/dev/null || echo "")
if [ -z "${PORTS_LIST}" ] && [ "${RESOURCE_TYPE}" != "pod" ]; then
  PORTS_LIST=$(kubectl get "${RESOURCE_TYPE}" "${RESOURCE_NAME}" -n "${NAMESPACE}" -o jsonpath='{range .spec.template.spec.containers[*].ports[*]}{.containerPort}{" "}{end}' 2>/dev/null || echo "")
fi

# 3. Discover environment variables that point to external services / databases
ENV_DUMP=$(kubectl get "${RESOURCE_TYPE}" "${RESOURCE_NAME}" -n "${NAMESPACE}" -o json 2>/dev/null || echo "{}")

DETECTED_EGRESS=""

# Check for database ports
if echo "${ENV_DUMP}" | grep -Ei "5432|postgres|psql" >/dev/null; then
  DETECTED_EGRESS="${DETECTED_EGRESS}
    # PostgreSQL Database Egress
    - to:
      - namespaceSelector: {}
        podSelector:
          matchLabels:
            app: postgres
      ports:
        - protocol: TCP
          port: 5432"
fi

if echo "${ENV_DUMP}" | grep -Ei "3306|mysql|mariadb" >/dev/null; then
  DETECTED_EGRESS="${DETECTED_EGRESS}
    # MySQL / MariaDB Egress
    - to:
      - namespaceSelector: {}
        podSelector:
          matchLabels:
            app: mysql
      ports:
        - protocol: TCP
          port: 3306"
fi

if echo "${ENV_DUMP}" | grep -Ei "6379|redis" >/dev/null; then
  DETECTED_EGRESS="${DETECTED_EGRESS}
    # Redis Cache Egress
    - to:
      - namespaceSelector: {}
        podSelector:
          matchLabels:
            app: redis
      ports:
        - protocol: TCP
          port: 6379"
fi

# Ingress ports block
INGRESS_PORTS_BLOCK=""
if [ -n "${PORTS_LIST}" ]; then
  INGRESS_PORTS_BLOCK="    ports:"
  for p in ${PORTS_LIST}; do
    INGRESS_PORTS_BLOCK="${INGRESS_PORTS_BLOCK}
      - protocol: TCP
        port: ${p}"
  done
fi

POLICY_YAML=$(cat << EOF
# Auto-generated by SecureKube NetworkPolicy Generator
# Workload: ${RESOURCE_TYPE}/${RESOURCE_NAME} (Namespace: ${NAMESPACE})
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: ${RESOURCE_NAME}-isolated-policy
  namespace: ${NAMESPACE}
  labels:
    app.kubernetes.io/managed-by: securekube-generator
spec:
  podSelector:
    matchLabels:
      ${PRIMARY_KEY}: "${PRIMARY_VAL}"
  policyTypes:
    - Ingress
    - Egress
  ingress:
    # Allow ingress within same namespace matching workload ports
    - from:
      - podSelector: {}
${INGRESS_PORTS_BLOCK}
  egress:
    # ── CRITICAL: CoreDNS Egress (Prevents silent DNS timeouts) ──────
    - to:
      - namespaceSelector:
          matchLabels:
            kubernetes.io/metadata.name: kube-system
        podSelector:
          matchLabels:
            k8s-app: kube-dns
      ports:
        - protocol: UDP
          port: 53
        - protocol: TCP
          port: 53
${DETECTED_EGRESS}
EOF
)

if [ -n "${OUTPUT_FILE}" ]; then
  echo "${POLICY_YAML}" > "${OUTPUT_FILE}"
  echo "✓ NetworkPolicy written to ${OUTPUT_FILE}" >&2
else
  echo "${POLICY_YAML}"
fi
